import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createStayFixture,stayCommand} from '../lib/stays/test-database.mjs';
import {DEMO_ACTOR,demoStays} from '../lib/stays/catalog.js';
test('management: ownership, approval, inventory blocks, versioning and audit',async t=>{
 const db=await createStayFixture();t.after(()=>db.close());
 const stranger='10000000-0000-4000-8000-000000000099';
 const manage=async(op,input={},actor=DEMO_ACTOR,admin=false)=>(await db.query('select reloo_stay_manage($1,$2,$3,$4) as d',[actor,admin,op,JSON.stringify(input)])).rows[0].d;
 const propertyId=demoStays[0].id,roomTypeId=demoStays[0].roomTypeId;
 assert.deepEqual((await manage('workspace',{},stranger)).properties,[]);
 await assert.rejects(manage('price',{propertyId,roomTypeId,nightlyPrice:1e6},stranger),/FORBIDDEN/);
 await assert.rejects(manage('create-room',{propertyId,name:'Missing capacity',nightlyPrice:500000}),/INVALID_INPUT/);
 const draft=await manage('create-property',{name:'Test property',city:'Demo city'});
 assert.equal(draft.status,'DRAFT');
 await manage('create-room',{propertyId:draft.id,name:'Test room type',capacity:2,nightlyPrice:500000});
 await manage('submit',{propertyId:draft.id});
 await assert.rejects(manage('approve',{propertyId:draft.id}),/FORBIDDEN/);
 assert.equal((await manage('approve',{propertyId:draft.id},stranger,true)).status,'APPROVED');
 await manage('price',{propertyId,roomTypeId,nightlyPrice:520000});
 assert.equal((await db.query('select version from stay_room_types where id=$1',[roomTypeId])).rows[0].version,2);
 const unitId='40000000-0000-4000-8000-000000000001';
 await manage('block',{propertyId,roomTypeId,unitId,startsAt:'2027-02-10T00:00Z',endsAt:'2027-02-12T00:00Z',reason:'Maintenance'});
 await assert.rejects(stayCommand(db,DEMO_ACTOR,'quote',{roomTypeId,checkIn:'2027-02-10',checkOut:'2027-02-11',guests:2}),/SOLD_OUT/);
 const workspace=await manage('workspace');assert.equal(workspace.blocks.length,1);
 await manage('unblock',{propertyId,roomTypeId,blockId:workspace.blocks[0].id});
 const q=await stayCommand(db,DEMO_ACTOR,'quote',{roomTypeId,checkIn:'2027-02-10',checkOut:'2027-02-11',guests:2});
 const order=await stayCommand(db,DEMO_ACTOR,'hold',{quoteId:q.id,key:'manager-hold-test',policyId:'DEMO_FLEX'});
 await assert.rejects(manage('block',{propertyId,roomTypeId,unitId,startsAt:'2027-02-10T00:00Z',endsAt:'2027-02-12T00:00Z',reason:'Maintenance'}),/SLOT_CONFLICT/);
 await assert.rejects(stayCommand(db,DEMO_ACTOR,'transition',{orderId:order.id,target:'COMPLETED',reason:'Bad transition'}),/INVALID_STATE/);
 await manage('add-unit',{propertyId,roomTypeId,name:'DEMO-02'});
 assert.ok(await stayCommand(db,stranger,'quote',{roomTypeId,checkIn:'2027-02-10',checkOut:'2027-02-11',guests:2}));
 await manage('suspend',{propertyId});
 await assert.rejects(stayCommand(db,stranger,'quote',{roomTypeId,checkIn:'2027-02-10',checkOut:'2027-02-11',guests:2}),/UNAVAILABLE/);
 await assert.rejects(db.query('update stay_management_audit set event=\'forged\''),/APPEND_ONLY/);
 assert.equal((await db.query("select has_function_privilege('anon','public.reloo_stay_manage(uuid,boolean,text,jsonb)','EXECUTE') as allowed")).rows[0].allowed,false);
 // Apply the project's complete lockdown after the additive booking migrations.
 await db.exec("create table profiles(role text,activation_status text,kyc_level text);create table assets(id text);create table security_audit(id text);create function reloo_record_screening(text,text,jsonb,text) returns text language sql as $$select 'test'::text$$;create function reloo_create_inquiry(text,text,jsonb) returns text language sql as $$select 'test'::text$$;");
 await db.exec(await readFile('deploy/vietnam/security-lockdown.sql','utf8'));
 for(const role of ['anon','authenticated'])for(const table of ['stay_properties','stay_room_types','stay_units','stay_quotes','stay_orders','stay_payment_events','stay_audit','stay_management_audit','stay_outbox'])assert.equal((await db.query('select has_table_privilege($1,$2,\'SELECT\') as allowed',[role,'public.'+table])).rows[0].allowed,false);
});
