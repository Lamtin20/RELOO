import { writeFile } from 'node:fs/promises';
import { CATEGORIES } from '../lib/constants.js';
import { getSpecFieldsForCategory } from '../lib/category-specs.js';
const schema = Object.fromEntries(CATEGORIES.map(({ id }) => [id, getSpecFieldsForCategory(id).fields.map(({ id, required, type, options }) => ({ id, required, type, ...(options ? { options } : {}) }))]));
const literal = JSON.stringify(schema).replaceAll("'", "''");
await writeFile(new URL('../deploy/vietnam/listing-required.sql', import.meta.url), `-- Generated by scripts/generate-listing-guard.mjs from the shared category definitions.
create or replace function public.reloo_listing_specs_gate()
returns trigger language plpgsql set search_path=public as $$
declare schema jsonb := '${literal}'::jsonb; field jsonb; value text;
begin
  if new.category is null or not (schema ? new.category) then raise exception 'LISTING_CATEGORY_REQUIRED' using errcode='23514'; end if;
  if new.specs is null or jsonb_typeof(new.specs)<>'object' then raise exception 'LISTING_SPECS_REQUIRED' using errcode='23514'; end if;
  for field in select * from jsonb_array_elements(schema->new.category) loop
    value := btrim(coalesce(new.specs->>(field->>'id'),''));
    if field->>'required'='true' and value='' then raise exception 'LISTING_SPEC_REQUIRED: %',field->>'id' using errcode='23514'; end if;
    if value<>'' then
      if jsonb_typeof(new.specs->(field->>'id')) not in ('string','number') then raise exception 'LISTING_SPEC_TYPE_INVALID' using errcode='23514'; end if;
      if length(value)>(case when field->>'type'='textarea' then 2000 else 300 end) then raise exception 'LISTING_SPEC_TOO_LONG' using errcode='23514'; end if;
      if field->>'type'='select' and not ((field->'options') ? value) then raise exception 'LISTING_SPEC_OPTION_INVALID' using errcode='23514'; end if;
      if field->>'type'='number' then
        if value !~ '^[0-9]+$' then raise exception 'LISTING_SPEC_NUMBER_INVALID' using errcode='23514'; end if;
        if value::numeric>9007199254740991 then raise exception 'LISTING_SPEC_NUMBER_INVALID' using errcode='23514'; end if;
      end if;
      if field->>'id'='year' and value::numeric not between 1886 and extract(year from current_date)+1 then raise exception 'LISTING_SPEC_YEAR_INVALID' using errcode='23514'; end if;
    end if;
  end loop;
  return new;
end $$;
revoke all on function public.reloo_listing_specs_gate() from public,anon,authenticated;
drop trigger if exists reloo_asset_specs_required on public.assets;
create trigger reloo_asset_specs_required before insert or update of category,specs on public.assets for each row execute function public.reloo_listing_specs_gate();
notify pgrst, 'reload schema';
`, 'utf8');
console.log('Generated database validation for listing categories and specifications.');
